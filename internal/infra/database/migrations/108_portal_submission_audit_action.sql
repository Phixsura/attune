-- Portal submission audit action allow-list.
--
-- The portal submission flow already emits `portal_submission.create` through
-- the audit log service. The existing database check constraint did not permit
-- that action, so the final audit write aborted the transaction and turned
-- successful portal submissions into 500s. This migration extends the allow
-- list to match the service-layer action registry.

