package main

import "github.com/Phixsura/attune/internal/pkg/ptrext"

type dashboard struct {
	UID         string         `json:"uid"`
	Title       string         `json:"title"`
	Description string         `json:"description"`
	Tags        []string       `json:"tags"`
	Timezone    string         `json:"timezone"`
	Schema      int            `json:"schemaVersion"`
	Version     int            `json:"version"`
	Refresh     string         `json:"refresh"`
	Time        map[string]any `json:"time"`
	Templating  map[string]any `json:"templating"`
	Links       []link         `json:"links,omitempty"`
	Panels      []panel        `json:"panels"`
	Filename    string         `json:"-"`
}

type link struct {
	Title       string `json:"title"`
	Type        string `json:"type"`
	UID         string `json:"uid"`
	IncludeVars bool   `json:"includeVars"`
	KeepTime    bool   `json:"keepTime"`
}

type panel struct {
	ID          int            `json:"id"`
	Type        string         `json:"type"`
	Title       string         `json:"title"`
	Description string         `json:"description,omitempty"`
	GridPos     gridPos        `json:"gridPos"`
	Targets     []target       `json:"targets,omitempty"`
	FieldConfig map[string]any `json:"fieldConfig,omitempty"`
	Options     map[string]any `json:"options,omitempty"`
}

type target struct {
	Expr         string `json:"expr"`
	Legend       string `json:"legendFormat,omitempty"`
	RefID        string `json:"refId"`
	Instant      bool   `json:"instant,omitempty"`
	Range        bool   `json:"range,omitempty"`
	Format       string `json:"format,omitempty"`
	EditorMode   string `json:"editorMode,omitempty"`
	Exemplar     bool   `json:"exemplar,omitempty"`
	Interval     string `json:"interval,omitempty"`
	IntervalFact int    `json:"intervalFactor,omitempty"`
}

type gridPos struct {
	H int `json:"h"`
	W int `json:"w"`
	X int `json:"x"`
	Y int `json:"y"`
}

type queryVar struct {
	Name       string         `json:"name"`
	Type       string         `json:"type"`
	Datasource any            `json:"datasource"`
	Query      string         `json:"query"`
	Refresh    int            `json:"refresh"`
	IncludeAll bool           `json:"includeAll"`
	Multi      bool           `json:"multi"`
	AllValue   string         `json:"allValue,omitempty"`
	Current    map[string]any `json:"current"`
}

const generatedDescription = "Generated by go run ./internal/tools/observabilitydash. Do not edit JSON by hand."

func newDashboard(uid, title, filename string, tags []string, vars ...queryVar) dashboard {
	return dashboard{
		UID:         uid,
		Title:       title,
		Description: generatedDescription,
		Tags:        append([]string{"attune"}, tags...),
		Timezone:    "browser",
		Schema:      39,
		Version:     1,
		Refresh:     "1m",
		Time:        map[string]any{"from": "now-6h", "to": "now"},
		Templating:  map[string]any{"list": vars},
		Filename:    filename,
	}
}

func tenantVar(metric string) queryVar {
	return queryVar{
		Name:       "tenant",
		Type:       "query",
		Datasource: nil,
		Query:      "label_values(" + metric + ", tenant)",
		Refresh:    1,
		IncludeAll: true,
		Multi:      true,
		AllValue:   ".*",
		Current:    map[string]any{"selected": true, "text": "All", "value": "$__all"},
	}
}

