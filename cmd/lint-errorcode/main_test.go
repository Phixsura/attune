func TestIsErrorResponseType_Ident(t *testing.T) {
	t.Parallel()

	require.True(t, isErrorResponseType(&ast.Ident{Name: "ErrorResponse"}))
	require.False(t, isErrorResponseType(&ast.Ident{Name: "OtherType"}))
}

func TestIsErrorResponseType_Selector(t *testing.T) {
	t.Parallel()

	require.True(t, isErrorResponseType(&ast.SelectorExpr{
		X:   &ast.Ident{Name: "attunev1"},
		Sel: &ast.Ident{Name: "ErrorResponse"},
	}))
	require.False(t, isErrorResponseType(&ast.SelectorExpr{
		X:   &ast.Ident{Name: "attunev1"},
		Sel: &ast.Ident{Name: "OtherType"},
	}))
}

func TestIsErrorResponseType_OtherExpr(t *testing.T) {
	t.Parallel()

	require.False(t, isErrorResponseType(&ast.BasicLit{Kind: token.STRING, Value: `"x"`}))
}

func TestIsCodeKey(t *testing.T) {
	t.Parallel()

	require.True(t, isCodeKey(&ast.Ident{Name: "Code"}))
	require.False(t, isCodeKey(&ast.Ident{Name: "Message"}))
	require.False(t, isCodeKey(&ast.BasicLit{Kind: token.STRING}))
}

func TestIsStringLiteral(t *testing.T) {
	t.Parallel()

	require.True(t, isStringLiteral(&ast.BasicLit{Kind: token.STRING, Value: `"hello"`}))
	require.False(t, isStringLiteral(&ast.BasicLit{Kind: token.INT, Value: "42"}))
	require.False(t, isStringLiteral(&ast.Ident{Name: "x"}))
}

func writeLintFixture(t *testing.T, src string) string {
	t.Helper()

	path := filepath.Join(t.TempDir(), "fixture.go")
	require.NoError(t, os.WriteFile(path, []byte(src), 0o600))
	return path
}
