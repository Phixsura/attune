func TestExpandPaths(t *testing.T) {
	t.Parallel()

	dir := t.TempDir()
	sub := filepath.Join(dir, "pkg")
	require.NoError(t, os.MkdirAll(sub, 0o755))
	require.NoError(t, os.WriteFile(filepath.Join(sub, "a.go"), []byte("package pkg"), 0o644))
	require.NoError(t, os.WriteFile(filepath.Join(sub, "b.txt"), []byte("not go"), 0o644))

	files, err := expandPaths([]string{dir + "/..."})
	require.NoError(t, err)
	require.Len(t, files, 1)
	require.Contains(t, files[0], "a.go")
}

