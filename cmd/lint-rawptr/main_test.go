// analyzeRawPtrSource parses an in-memory Go source string and returns
// the lint findings. The file is written to a temp dir so the analyser's
// os.ReadFile path works, but the path is excluded from the expandPaths
// skip-list (it's not under internal/pkg/ptrext, cmd/lint-rawptr, etc.).
func analyzeRawPtrSource(t *testing.T, src string) []finding {
	t.Helper()
	dir := t.TempDir()
	f := filepath.Join(dir, "input.go")
	require.NoError(t, os.WriteFile(f, []byte(src), 0o644))
	fset := token.NewFileSet()
	findings, err := analyzeFile(fset, f, false)
	require.NoError(t, err)
	return findings
}

